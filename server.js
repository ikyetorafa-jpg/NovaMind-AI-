// Helper function to handle retries on 503 / 429 temporary errors
async function fetchGeminiWithRetry(promptMessage, retries = 3, delayMs = 1000) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent?key=${GEMINI_API_KEY}`;
    
    const payload = {
        contents: [
            {
                parts: [
                    { text: promptMessage }
                ]
            }
        ]
    };

    for (let attempt = 1; attempt <= retries; attempt++) {
        try {
            const response = await fetch(url, {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify(payload)
            });

            // If 503 (Overloaded) or 429 (Rate Limit) and we have retries left, wait and try again
            if ((response.status === 503 || response.status === 429) && attempt < retries) {
                console.warn(`[Gemini API] Server busy (${response.status}). Retrying attempt ${attempt}/${retries} in ${delayMs}ms...`);
                await new Promise(resolve => setTimeout(resolve, delayMs));
                delayMs *= 2; // Increase wait time exponentially (1s, 2s, 4s)
                continue;
            }

            return response;
        } catch (err) {
            if (attempt === retries) throw err;
            await new Promise(resolve => setTimeout(resolve, delayMs));
            delayMs *= 2;
        }
    }
}

const server = http.createServer(async (req, res) => {
    // Serve the website
    if (req.method === "GET" && req.url === "/") {
        const html = fs.readFileSync(
            path.join(__dirname, "index.html"),
            "utf8"
        );

        res.writeHead(200, { "Content-Type": "text/html" });
        res.end(html);
        return;
    }

    // AI endpoint
    if (req.method === "POST" && req.url === "/chat") {
        let body = "";

        req.on("data", chunk => {
            body += chunk;
        });

        req.on("end", async () => {
            try {
                const data = JSON.parse(body);

                // Send request with retry mechanism
                const response = await fetchGeminiWithRetry(data.message || "Hello");
                const result = await response.json();

                // Handle API error response from Google
                if (!response.ok) {
                    res.writeHead(response.status, { "Content-Type": "application/json" });
                    res.end(JSON.stringify({
                        reply: `API Error (${response.status}): ${result.error?.message || "Server busy or quota reached."}`
                    }));
                    return;
                }

                // Safely parse candidate text
                const candidate = result.candidates?.[0];
                let replyText = candidate?.content?.parts?.[0]?.text;

                if (!replyText) {
                    if (candidate?.finishReason && candidate.finishReason !== "STOP") {
                        replyText = `[Response filtered by Gemini due to: ${candidate.finishReason}]`;
                    } else {
                        replyText = "No response generated by model.";
                    }
                }

                res.writeHead(200, { "Content-Type": "application/json" });
                res.end(JSON.stringify({ reply: replyText }));

            } catch (error) {
                res.writeHead(500, { "Content-Type": "application/json" });
                res.end(JSON.stringify({ reply: `Server Error: ${error.message}` }));
            }
        });

        return;
    }

    res.writeHead(404);
    res.end("Not found");
});

server.listen(PORT, "0.0.0.0", () => {
    console.log(`NovaMind running on port ${PORT}`);
});